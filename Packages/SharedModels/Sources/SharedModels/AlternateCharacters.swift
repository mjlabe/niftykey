import Foundation

public struct AlternateCharacters: Sendable {
    public static let map: [String: [String]] = [
        "a": ["à", "á", "â", "ä", "æ", "ã", "å", "ā"],
        "c": ["ç", "ć", "č"],
        "e": ["è", "é", "ê", "ë", "ē", "ė", "ę"],
        "i": ["î", "ï", "í", "ī", "į", "ì"],
        "l": ["ł"],
        "n": ["ñ", "ń"],
        "o": ["ô", "ö", "ò", "ó", "œ", "ø", "ō", "õ"],
        "s": ["ß", "ś", "š"],
        "u": ["û", "ü", "ù", "ú", "ū"],
        "y": ["ÿ"],
        "z": ["ž", "ź", "ż"],
        "0": ["°"],
        "1": ["¹", "½", "⅓", "¼"],
        "2": ["²", "⅔"],
        "3": ["³", "¾"],
        "4": ["⁴"],
        "5": ["⅕"],
        "-": ["–", "—", "•"],
        "/": ["\\"],
        "$": ["€", "£", "¥", "₩", "₹", "¢"],
        "&": ["§"],
        "\"": ["\u{201C}", "\u{201D}", "\u{00AB}", "\u{00BB}"],
        ".": ["…"],
        "?": ["¿"],
        "!": ["¡"],
        "'": ["\u{2018}", "\u{2019}", "`"],
        "%": ["‰"],
    ]

    public static func alternates(for key: String) -> [String]? {
        map[key.lowercased()]
    }
}
